// Writes sw.js with the list of files to cache for offline play and a version hash of their contents.
// Run after changing any game file: `npm run build`
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const include = ['index.html', 'manifest.webmanifest', 'vendor/phaser.min.js'];
const walk = (dir) => fs.readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap(d => d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]);
for (const dir of ['src', 'levels', 'icons']) include.push(...walk(dir).filter(f => /\.(js|json|png)$/.test(f)));
include.sort();
const hash = crypto.createHash('sha1');
for (const f of include) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest('hex').slice(0, 10);
const sw = `// Generated by scripts/build-sw.mjs — do not edit by hand.
// Caches the whole game on first load so it plays offline (cache-first, refreshed when the version changes).
const VERSION = '${version}';
const CACHE = 'lw-stars-' + VERSION;
const FILES = ${JSON.stringify(['./', ...include], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('lw-stars-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
      return res;
    }).catch(() => (e.request.mode === 'navigate' ? caches.match('./index.html') : undefined)))
  );
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
console.log(`sw.js: ${include.length + 1} files, version ${version}`);
